// Weighted statistics over a finished book set. Because the RGS samples books by
// their lookup-table weight, these figures are exact for the published files
// (they are not estimates of an infinite game).
import { WINCAP } from '../engine/config.ts';
import type { Book } from '../engine/types.ts';

export type BookSummary = Pick<Book, 'id' | 'payoutMultiplier' | 'tags' | 'criteria'>;

export interface ModeStats {
  mode: string;
  cost: number;
  books: number;
  nonZeroWeightBooks: number;
  rtp: number;
  rawRtp: number;
  hitRate: number;
  stdDev: number; // in x bet
  maxWin: number; // x bet
  maxWinProbability: number;
  zeroProbability: number;
  aboveScale: number;
  fixedGroups: { name: string; probability: number; books: number }[];
  features: { tag: string; probability: number; oneIn: number; rtpContribution: number; avgWin: number }[];
  buckets: { label: string; probability: number }[];
  sim: {
    natural: number;
    naturalCaps: number;
    naturalBreach: number;
    forcedAttempts: number;
    forcedHits: number;
    wincapEstimate: number;
  };
  seconds: number;
}

const BUCKETS: [number, number, string][] = [
  [0, 0, '0x'],
  [0.01, 1, '>0x to <1x'],
  [1, 2, '1x to <2x'],
  [2, 5, '2x to <5x'],
  [5, 10, '5x to <10x'],
  [10, 20, '10x to <20x'],
  [20, 50, '20x to <50x'],
  [50, 100, '50x to <100x'],
  [100, 500, '100x to <500x'],
  [500, 1000, '500x to <1,000x'],
  [1000, 5000, '1,000x to <5,000x'],
  [5000, 5000, '5,000x (win cap)'],
];

export function buildStats(
  mode: string,
  cost: number,
  books: BookSummary[],
  weights: number[],
  extra: ModeStats['sim'] & { rawRtp: number; zeroProbability: number; aboveScale: number; fixedGroups: ModeStats['fixedGroups']; seconds: number },
): ModeStats {
  const W = weights.reduce((a, b) => a + b, 0);
  const p = (i: number) => weights[i] / W;
  let mean = 0;
  let hit = 0;
  let maxWin = 0;
  let maxP = 0;
  books.forEach((b, i) => {
    const x = b.payoutMultiplier / 100;
    mean += p(i) * x;
    if (x > 0) hit += p(i);
    if (b.payoutMultiplier >= WINCAP) maxP += p(i);
    maxWin = Math.max(maxWin, x);
  });
  // Modes that cannot reach the cap report the frequency of their largest payout instead.
  if (maxP === 0) books.forEach((b, i) => { if (b.payoutMultiplier / 100 === maxWin) maxP += p(i); });
  let variance = 0;
  books.forEach((b, i) => (variance += p(i) * (b.payoutMultiplier / 100 - mean) ** 2));

  const tagAgg = new Map<string, { prob: number; win: number }>();
  books.forEach((b, i) => {
    for (const t of b.tags) {
      if (t === 'forced') continue;
      const a = tagAgg.get(t) ?? { prob: 0, win: 0 };
      a.prob += p(i);
      a.win += p(i) * (b.payoutMultiplier / 100);
      tagAgg.set(t, a);
    }
  });
  const features = [...tagAgg.entries()]
    .map(([tag, a]) => ({ tag, probability: a.prob, oneIn: 1 / a.prob, rtpContribution: a.win / cost, avgWin: a.win / a.prob }))
    .sort((a, b) => b.probability - a.probability);

  const buckets = BUCKETS.map(([lo, hi, label]) => {
    let prob = 0;
    books.forEach((b, i) => {
      const x = b.payoutMultiplier / 100;
      const inside = lo === hi ? x === lo : x >= lo && x < hi;
      if (inside) prob += p(i);
    });
    return { label, probability: prob };
  });

  return {
    mode,
    cost,
    books: books.length,
    nonZeroWeightBooks: weights.filter((w) => w > 0).length,
    rtp: mean / cost,
    rawRtp: extra.rawRtp,
    hitRate: hit,
    stdDev: Math.sqrt(variance),
    maxWin,
    maxWinProbability: maxP,
    zeroProbability: extra.zeroProbability,
    aboveScale: extra.aboveScale,
    fixedGroups: extra.fixedGroups,
    features,
    buckets,
    sim: {
      natural: extra.natural,
      naturalCaps: extra.naturalCaps,
      naturalBreach: extra.naturalBreach,
      forcedAttempts: extra.forcedAttempts,
      forcedHits: extra.forcedHits,
      wincapEstimate: extra.wincapEstimate,
    },
    seconds: extra.seconds,
  };
}

const pct = (v: number, d = 3) => `${(v * 100).toFixed(d)}%`;
const oneIn = (v: number) => (v > 0 ? `1 in ${(1 / v < 100 ? (1 / v).toFixed(2) : Math.round(1 / v).toLocaleString('en-US'))}` : 'never');

export function renderReport(modes: ModeStats[], args: { books: number; seed: number; target: number }): string {
  const out: string[] = [];
  out.push('# Midnight Vault: math report', '');
  out.push(`Generated by \`src/math/cli.ts\` with seed ${args.seed}, ${args.books.toLocaleString('en-US')} natural books per mode, target RTP ${pct(args.target, 2)}.`);
  out.push('Figures are exact for this book set and its lookup-table weights. They are not a certification.', '');
  out.push('| Mode | Cost | Books | RTP | Raw sim RTP | Hit rate | Std dev | Max win | Max win frequency |');
  out.push('|---|---|---|---|---|---|---|---|---|');
  for (const m of modes) {
    out.push(`| ${m.mode} | ${m.cost}x | ${m.books.toLocaleString('en-US')} | ${pct(m.rtp)} | ${pct(m.rawRtp, 2)} | ${oneIn(m.hitRate)} | ${m.stdDev.toFixed(2)}x | ${m.maxWin.toLocaleString('en-US')}x | ${oneIn(m.maxWinProbability)} |`);
  }
  for (const m of modes) {
    out.push('', `## ${m.mode} mode`, '');
    out.push(`- Non-zero-weight books: ${m.nonZeroWeightBooks.toLocaleString('en-US')}`);
    out.push(`- Probability of a round paying less than its cost, after weighting: ${pct(m.zeroProbability, 2)}`);
    out.push(`- Weighting adjustment: rounds paying at least the cost are ${m.aboveScale.toFixed(4)}x as likely as in the raw simulation`);
    out.push(`- Win-cap estimate: natural cap hits ${m.sim.naturalCaps} / ${m.sim.natural.toLocaleString('en-US')}; natural Cursed Fortune rounds ${m.sim.naturalBreach}; forced Cursed Fortune cap rate ${m.sim.forcedHits} / ${m.sim.forcedAttempts}; probability used ${m.sim.wincapEstimate.toExponential(3)}`);
    for (const g of m.fixedGroups) out.push(`- Fixed-probability group \`${g.name}\`: ${g.books} books sharing probability ${g.probability.toExponential(3)} (${oneIn(g.probability)})`);
    out.push('', '| Feature tag | Frequency | RTP contribution | Average round win |', '|---|---|---|---|');
    for (const f of m.features) out.push(`| ${f.tag} | ${oneIn(f.probability)} | ${pct(f.rtpContribution, 2)} | ${f.avgWin.toFixed(2)}x |`);
    out.push('', '| Round win | Probability |', '|---|---|');
    for (const b of m.buckets) out.push(`| ${b.label} | ${pct(b.probability, 4)} |`);
  }
  out.push('');
  return out.join('\n');
}
